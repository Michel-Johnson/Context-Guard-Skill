import assert from 'node:assert/strict';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readJSON } from './history.mjs';
const here = path.dirname(fileURLToPath(import.meta.url));
const runtime = await readJSON(path.join(here, process.argv[2] === 'calibration' ? 'calibration-runtime.json' : 'runtime.json'));
const { browserToken } = await readJSON(path.resolve(here, '../local-coordinator-data/local-config.json'));
const headers = { Authorization: `Bearer ${browserToken}`, 'Content-Type': 'application/json' };
const call = (route, options = {}) => fetch(runtime.baseUrl + route, { ...options, headers: { ...headers, ...options.headers } });
assert.equal((await fetch(runtime.baseUrl + '/experiment/meta')).status, 401);
const meta = await call('/experiment/meta'); assert.equal(meta.status, 200);
assert.equal(JSON.stringify(await meta.json()).includes('adaptive'), false);
const page = await call('/projects/codex-learning'); assert.equal(page.status, 200); assert.match(await page.text(), /\/experiment\/ui.js/);
const app = await call('/projects/workbench-app.js'); assert.equal(app.status, 200); assert.match(await app.text(), /window.installLearningCoordinator/);
const source = await call('/experiment/source?path=codex-rs%2Fcli%2Fsrc%2Fmain.rs&line=1013'); assert.equal(source.status, 200); assert.match(await source.text(), /fn main/);
assert.equal((await call('/experiment/source?path=..%2Fprovider.json')).status, 400);
assert.equal((await call('/experiment/tasks', { method: 'POST', headers: { Origin: 'https://example.com' }, body: '{}' })).status, 403);
assert.equal((await call('/api/projects/codex-learning/snapshot', { method: 'POST', body: '{}' })).status, 403);
const presence = await call('/api/workbench/projects/codex-learning/api/presence?view=main', { method: 'POST', body: JSON.stringify({ clientId: 'http-calibration', version: null, dirty: false }) });
assert.equal(presence.status, 200, await presence.text());
console.log('HTTP checks passed: auth, UI adapter, source links, traversal, origin, read-only map, heartbeat.');
